def run_static_ptq_optimum(fp32_model, tokenizer, dl, out_dir="tinyllama-int8-static"):
    # Setup quantization
    import torch.nn as nn
    print("\n[2] Setting up quantization...")
    qconfig = QConfig(
        activation=HistogramObserver.with_args(reduce_range=True),
        weight=MinMaxObserver.with_args(
            dtype=torch.qint8,
            qscheme=torch.per_tensor_affine  # Supported
        )
    )
    fp32_model.qconfig = qconfig

    # Prepare (insert observers)
    print("\n[3] Preparing model...")
    prepare(fp32_model, inplace=True)
     # IMPORTANT: Skip embedding layers from quantization
    def skip_embedding_quant(module):
        """Skip quantization for Embedding layers"""
        for name, submodule in module.named_modules():
            if isinstance(submodule, nn.Embedding):
                print(f"  ⊘ Skipping quantization for: {name}")
                submodule.qconfig = None

    skip_embedding_quant(fp32_model)
    print("  ✓ Embedding layers skipped")
    print("Observers inserted")
    with torch.no_grad():
        for i, batch in enumerate(dl):
            # print(batch)
            # batch = [for]
            fp32_model(**batch)
            if (i + 1) % 25 == 0:
                print(f"   {i + 1}/100")
    print(" Calibration done")

    # Convert to INT8
    print("\n[5] Converting to INT8...")
    model_int8 = convert(fp32_model, inplace=False)
    ptq_size_mb = save_and_size(model_int8, tokenizer, out_dir="tinyllama_fp32")
    ptq_metrics = measure_generate(model_int8, tokenizer, "Explain quantization in one paragraph for ML engineers")
    ptq_ppl = compute_perplixity(model_int8, tokenizer)
    print(" Conversion done")
    print_row("PTQ INT8", ptq_size_mb, ptq_metrics.latency_s,
          ptq_metrics.tokens_per_sec, ptq_metrics.peak_gpu_mem_mb,ptq_ppl)

run_static_ptq_optimum(fp32_model, tokenizer, dl)



