def prepare_data(tokenizer, calib_texts, batch_size = 4,max_length=256):

    class CalibDataSet(Dataset):
        def __init__(self, texts_):
            self.texts = texts_
        def __len__(self):
            return len(self.texts)
        def __getitem__(self, ind):
            txt = self.texts[ind]
            enc = tokenizer(txt, truncation=True,
                max_length=max_length, return_tensors="pt")
            return {k: v.squeeze(0) for k, v in enc.items()}
    pad_id = tokenizer.pad_token_id
    print('pad_id=',pad_id)
    if pad_id is None:
        # Fallback to EOS if the tokenizer has no dedicated PAD
        pad_id = tokenizer.eos_token_id

    def _collate(batch):
        input_ids_list = [b["input_ids"].to(device) for b in batch]
        if "attention_mask" in batch[0]:
            attn_list = [b["attention_mask"].to(device) for b in batch]
        else:
            # Fallback: all real tokens treated as 1s
            attn_list = [torch.ones_like(b["input_ids"].to(device)) for b in batch]

        input_ids = pad_sequence(input_ids_list, batch_first=True, padding_value=pad_id)
        attention = pad_sequence(attn_list, batch_first=True, padding_value=0)
        return {"input_ids": input_ids, "attention_mask": attention}
    ds = CalibDataSet(calib_texts)
    return DataLoader(ds, batch_size=batch_size, shuffle=False, collate_fn=_collate)

