def dir_size_mb(path: str) -> float:
    total = 0
    for root, _, files in os.walk(path):
        for f in files:
            total += os.path.getsize(os.path.join(root, f))
    return total / (1024**2)

def save_and_size(model, tokenizer, out_dir)-> float:
  if os.path.exists(out_dir):
    shutil.rmtree(out_dir)
  os.makedirs(out_dir, exist_ok=True)
  # name = os.path.join(out_dir, "model")
  model.save_pretrained(out_dir)
  tokenizer.save_pretrained(out_dir,safe_serialization=True)
  return dir_size_mb(out_dir)

@torch.no_grad()
def compute_perplixity(model, tokenizer, seq_len = 128):
  eval_text = "In the rapidly evolving landscape of modern technology, artificial intelligence stands out as a transformative force that is fundamentally reshaping how humanity interacts, works, and solves complex problems across global industries, because its advanced machine learning algorithms can analyze vast datasets with unprecedented speed, automate intricate workflows, and generate human-like insights, which ultimately empowers businesses to optimize their efficiency, assists doctors in diagnosing critical illnesses more accurately, and enables developers to create highly innovative software solutions that were completely unimaginable just a few short decades ago, paving the way toward a highly connected and intelligent future."
  input_tokens = tokenizer(eval_text, return_tensors="pt")
  input_ids = input_tokens['input_ids'][0]
  loss_total = 0.0
  total_token = 0
  model.eval()
  for start in range(0, len(input_ids) - seq_len, seq_len):
    chunk = input_ids[start:start + seq_len + 1]
    inp    = chunk[:-1].unsqueeze(0).to(device)
    labels = chunk[1:].unsqueeze(0).to(device)
    out = model(input_ids = inp, labels = labels)
    loss_total += float(out.loss * labels.numel())
    total_token += labels.numel()
  loss = loss_total / total_token
  return math.exp(loss)

@contextlib.contextmanager
def torch_cuda_monitor():
  if device == "cuda":
    torch.cuda.reset_peak_memory_stats()
    torch.cuda.synchronize()
    try:
      yield
    finally:
      torch_cuda_monitor.peak_mb = torch.cuda.max_memory_allocated() / (1024**2)
      torch_cuda_monitor.start_mb = torch.cuda.memory_allocated() / (1024**2)
      torch.cuda.empty_cache()
    torch.cuda.synchronize()
  else:
    try:
      yield
    finally:
      torch_cuda_monitor.peak_mb = 0.0
      torch_cuda_monitor.start_mb = 0.0

"""# Measure Text Generation Performance
This function:
- Measures the latency, throughput, and peak GPU memory usage during text generation.
- Performs a warmup run to stabilize performance.
- Uses multiple runs to calculate average metrics for better accuracy.
"""

def measure_generate(model, tokenizer, prompt, max_new_token = 64, runs = 3)->GenMetrics:
  model.eval()
  #tokenize the prompt and move to device
  tokens = tokenizer(prompt, return_tensors ="pt")
  tokens= {k:v.to(device) for k, v in tokens.items()}
  input_len = tokens['input_ids'].shape[1]
  total_latencies = []
  tps = []
  #warmup
  with torch.no_grad():
      _ = model.generate(**tokens, max_new_tokens=8, do_sample=False, use_cache=True)
  with torch_cuda_monitor():
    for _ in range(runs):
      if device == "cuda":
        torch.cuda.synchronize()

      with torch.no_grad():
        start = time.perf_counter()
        out = model.generate(**tokens, max_new_tokens=max_new_token, do_sample=False, use_cache=True)
      if device == "cuda":
        torch.cuda.synchronize()
      end = time.perf_counter()
      lat = end - start
      total_latencies.append(lat)
      gen_token = out.shape[1] - input_len
      tps.append(gen_token / lat)
      return GenMetrics(sum(total_latencies)/len(total_latencies),
                        sum(tps)/len(tps),
                        getattr(torch_cuda_monitor, "peak_mb", 0.0))

